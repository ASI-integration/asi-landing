/**
 * Source proposal -> existing Publisher task-shape preflight.
 * No host authority, GitHub port, code execution, filesystem mutation,
 * credentials, or approval can be derived from a model's proposed source.
 *
 * The existing Publisher still requires a distinct authenticated catalog
 * workOrderId, native admission, protected reviewer and exact CI. In
 * particular G2 live Change Preparer remains limited to two witnesses.
 */
import {createHash} from 'node:crypto';
import {inspectSourceIntake} from './source-work-intake.mjs';

const REPO='ASI-integration/asi-landing';
const H64=/^[a-f0-9]{64}$/;
const digest=x=>createHash('sha256').update(x).digest('hex');
const denied=reason=>Object.freeze({schema:'asi.source-publisher-handoff.v1',
  status:'BLOCKED',reason,authorized:false,task:null});
const plain=o=>o!==null&&typeof o==='object'&&!Array.isArray(o)&&
  (Object.getPrototypeOf(o)===Object.prototype||Object.getPrototypeOf(o)===null)&&
  Reflect.ownKeys(o).every(k=>typeof k==='string'&&Object.hasOwn(
    Object.getOwnPropertyDescriptor(o,k),'value'));
const array=a=>Array.isArray(a)&&Object.getPrototypeOf(a)===Array.prototype&&
  Reflect.ownKeys(a).length===a.length+1&&
  a.every((_,i)=>Object.hasOwn(a,i));
const PATH=/^[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_.-]+)*\.(?:py|js|mjs|json)$/;

export function compileSourcePublisherHandoff({task,admittedTasks,proposal}={}){
  try{
    const intake=inspectSourceIntake({task,admittedTasks});
    if(intake.status!=='SOURCE_CANDIDATE')return denied('UNADMITTED_SOURCE_TASK');
    if(!plain(proposal)||proposal.schema!=='asi.source-intake-result.v1'||
       proposal.status!=='PROPOSAL_PREPARED'||proposal.authorized!==false||
       proposal.taskBinding!==intake.taskBinding||!plain(proposal.candidate))
      return denied('SOURCE_PROPOSAL_NOT_EXACTLY_BOUND');
    const p=proposal.candidate;
    if(p.id!==task.id||p.laneId!==task.laneId||
       p.baseSha!==task.baseSha||p.branch!==task.branch||
       !H64.test(p.changeDigest)||!array(p.changes)||
       p.changes.length!==task.files.length)
      return denied('PROPOSAL_IDENTITY_OR_SCOPE_CHANGED');
    const checked=[];
    for(let i=0;i<task.files.length;i++){
      const expected=task.files[i],change=p.changes[i];
      if(!plain(change)||change.path!==expected.path||
         change.beforeSha256!==expected.beforeSha256||
         typeof change.content!=='string'||!H64.test(change.afterSha256)||
         digest(change.content)!==change.afterSha256)
        return denied('SOURCE_BYTES_OR_PRECONDITION_CHANGED');
      if(!PATH.test(change.path) || change.path.split('/').some(s=>
        !s||s==='.'||s==='..'||s.toLowerCase()==='.git'))
        return denied('NO_EXISTING_PREPARER_SYNTAX_FOR_PATH');
      // Existing preparer reformats JSON source; ensure generated bytes
      // already match the exact canonical byte form before admission.
      if(change.path.endsWith('.json')){
        let normalized;
        try{normalized=JSON.stringify(JSON.parse(change.content),null,2)+'\n';}
        catch{return denied('JSON_SYNTAX_UNVERIFIED');}
        if(change.content!==normalized)return denied('JSON_BYTES_REQUIRE_CANONICALIZATION');
      }
      checked.push(Object.freeze({path:change.path,
        beforeSha256:change.beforeSha256,content:change.content,
        afterSha256:change.afterSha256}));
    }
    const proof=digest(JSON.stringify(checked.map(
      ({path,beforeSha256,afterSha256})=>({path,beforeSha256,afterSha256}))));
    if(proof!==p.changeDigest)return denied('PROPOSAL_DIGEST_CHANGED');
    return Object.freeze({schema:'asi.source-publisher-handoff.v1',
      status:'SOURCE_PREPARER_CANDIDATE',authorized:false,
      reason:'REQUIRES_SIGNED_WORK_ORDER_NATIVE_LOCK_EXISTING_PREPARER_AND_PUBLISHER',
      sourceBinding:intake.taskBinding,proposalDigest:proof,
      // The output branch is separate from the owner workstream's branch.
      // This branch is NOT approved until included in a real signed catalog.
      task:Object.freeze({id:task.id,repo:REPO,stage:task.stage,
        sha:task.baseSha,kind:'github-publisher',pr:null,
        branch:'asi/engine-task/'+task.id,laneId:task.laneId,
        changes:Object.freeze(checked)})});
  }catch{return denied('UNREADABLE_OR_MUTATED_SOURCE');}
}
