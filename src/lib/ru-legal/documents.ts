export function canonicalRuLegalDocumentContent(document: RuLegalDocument): string {
  return JSON.stringify({
    type: document.type,
    version: document.version,
    title: document.title,
    subtitle: document.subtitle,
    sections: document.sections.map((section) => ({
      heading: section.heading,
      paragraphs: [...section.paragraphs],
    })),
  });
}

export function ruLegalDocumentSha256(document: RuLegalDocument): string {
  return createHash('sha256').update(canonicalRuLegalDocumentContent(document), 'utf8').digest('hex');
}

export function isRuLegalDocumentType(value: unknown): value is RuLegalDocumentType {
  return value === 'offer' || value === 'personal_data_consent';
}
